async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1536, height: 1000 })
  await page.goto('http://127.0.0.1:4191/runs/inspector-example')
  await page.getByRole('button', { name: 'Inspect classify', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const pane = name => dialog.getByRole('region', { name, exact: true })
  await pane('Input').getByRole('cell', { name: 'item-01', exact: true }).waitFor()
  await pane('Input').getByRole('button', { name: 'Inspect input item 2' }).click()
  check((await pane('Input').innerText()).includes('Item 2'), 'Selected record missing')
  check(await pane('Input').getByRole('button', { name: 'Copy item' }).isVisible(), 'Copy selected record missing')
  check(await pane('Input').locator('.record-fields').isVisible(), 'Readable record fields missing')
  await pane('Input').getByRole('button', { name: 'Table', exact: true }).click()
  await pane('Input').getByRole('searchbox').fill('item-01')
  check(await pane('Input').getByRole('cell', { name: 'item-02', exact: true }).count() === 0, 'Input search did not filter')
  await pane('Input').getByRole('searchbox').fill('')
  await pane('Input').getByRole('button', { name: 'JSON', exact: true }).click()
  check((await pane('Input').locator('pre').innerText()).includes('never-load'), 'Raw input lost')
  check(await page.evaluate(() => !window.__inspectionXss && !document.querySelector('img[src*="never-load"]')), 'Saved data became executable markup')
  await pane('Input').getByRole('button', { name: 'Table', exact: true }).click()
  check(await pane('Input').locator('tbody tr').first().evaluate(row => row.getBoundingClientRect().height < 110), 'Long table row is not compact')
  await pane('Input').getByRole('button', { name: 'Inspect input item 2' }).click()
  await page.screenshot({ path: '../docs/screenshots/step-inspector.png' })
  await dialog.getByRole('tab', { name: 'Calls 3', exact: true }).click()
  await pane('Prompt').getByText(/Classify the supplied feedback/).waitFor()
  await pane('Output').getByRole('button', { name: 'Original', exact: true }).click()
  check((await pane('Output').locator('pre').innerText()).startsWith('```json'), 'Original response framing was lost')
  await pane('Output').getByRole('button', { name: 'Record', exact: true }).click()
  await pane('Output').getByText('positive', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: 'item-02 · retry', exact: true }).click()
  await dialog.getByRole('button', { name: 'Previous attempt: call-2' }).waitFor()
  await page.screenshot({ path: '../docs/screenshots/step-inspector-calls.png' })
  await dialog.getByRole('button', { name: 'Previous attempt: call-2' }).click()
  await dialog.getByText('The response was not valid JSON.', { exact: true }).waitFor()
  check((await pane('Output').innerText()).includes('The feedback is negative.'), 'Failed response lost')
  await dialog.getByRole('searchbox', { name: 'Search calls' }).fill('item-02')
  check(await dialog.locator('.inspection-call-table tbody tr').count() === 2, 'Record ID search lost retry')
  await dialog.getByLabel('Call result filter').selectOption('failed')
  check(await dialog.locator('.inspection-call-table tbody tr').count() === 1, 'Failed call filter wrong')
  await dialog.getByRole('searchbox', { name: 'Search calls' }).fill('no-such-record')
  await dialog.getByText(/No matching calls/).waitFor()
  await dialog.getByRole('tab', { name: 'Files 12', exact: true }).click()
  await dialog.getByRole('button', { name: /classify\/results\/many-records.json/ }).click()
  await pane('File').getByLabel('File collection').selectOption('records')
  check((await pane('File').innerText()).includes('1–15 of 31'), 'First page missing')
  await pane('File').getByRole('button', { name: 'Next', exact: true }).click()
  check((await pane('File').innerText()).includes('16–30 of 31'), 'Pagination broken')
  await pane('File').getByRole('searchbox').fill('record-31')
  await pane('File').getByRole('cell', { name: 'record-31', exact: true }).waitFor()
  await dialog.getByRole('button', { name: /classify\/results\/large.txt/ }).click()
  await pane('File').getByText(/too large for an inline preview/).waitFor()
  check(await pane('File').getByRole('link', { name: 'Raw file' }).isVisible(), 'Large file download missing')
  await dialog.getByRole('button', { name: /classify\/results\/missing.txt/ }).click()
  await pane('File').getByText(/not included or is missing/).waitFor()
  await dialog.getByRole('button', { name: /classify\/results\/summary.md/ }).click()
  await pane('File').getByRole('heading', { name: 'Feedback summary' }).waitFor()
  check(await page.evaluate(() => !window.__inspectionXss), 'Markdown executed script')
  await dialog.getByRole('tab', { name: 'Checks 1/1', exact: true }).click()
  await dialog.getByText('Both records have a valid sentiment and confidence.', { exact: true }).waitFor()
  await dialog.getByRole('tab', { name: 'Checks 1/1', exact: true }).press('Home')
  check(await dialog.getByRole('tab', { name: 'Step', exact: true }).getAttribute('aria-selected') === 'true', 'Keyboard tabs broken')
  await dialog.getByRole('button', { name: 'Inspect step report' }).click()
  await pane('Prompt').getByText(/Summarize the classified feedback/).waitFor()
  await dialog.getByRole('tab', { name: 'Calls 0' }).click()
  await dialog.getByRole('heading', { name: 'No individual calls recorded' }).waitFor()
  await dialog.getByRole('button', { name: 'Inspect step classify' }).click()
  await dialog.getByRole('tab', { name: 'Step', exact: true }).click()
  await pane('Input').getByRole('button', { name: 'Table', exact: true }).click()
  await pane('Input').getByRole('cell', { name: 'item-01', exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page overflows horizontally')
  await page.screenshot({ path: '../docs/screenshots/step-inspector-mobile.png' })
  await page.setViewportSize({ width: 1536, height: 1000 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.screenshot({ path: '../docs/screenshots/step-inspector-dark.png' })
  await page.emulateMedia({ colorScheme: 'light' })
  await dialog.getByRole('button', { name: 'Close step inspector' }).focus()
  await page.keyboard.press('Shift+Tab')
  check(await page.evaluate(() => Boolean(document.activeElement.closest('[role="dialog"]'))), 'Focus escaped modal')
  await page.keyboard.press('Escape')
  check(await dialog.count() === 0, 'Escape did not close')
  check(await page.getByRole('button', { name: 'Inspect classify', exact: true }).evaluate(node => node === document.activeElement), 'Focus not restored')
  await page.getByRole('link', { name: 'Инструкция', exact: true }).click()
  await page.getByRole('dialog', { name: 'Инструкция', exact: true }).getByRole('heading', { name: 'Как читать результаты в Flora' }).waitFor()
  await page.keyboard.press('Escape')
  await page.goto('http://127.0.0.1:4191/runs/inspector-legacy')
  await page.getByRole('button', { name: 'Inspect review', exact: true }).click()
  await pane('Input').getByText(/did not save input-file snapshots/).waitFor()
  check(errors.length === 0, errors.join('\n'))
  return 'PASS: inputs, record search/selection, calls/retry/filter, files, pagination, missing/large files, Markdown/XSS, responsive/dark, keyboard/focus, legacy history'
}
